"""Сумма прописью для акта: 2800 → «две тысячи восемьсот рублей 00 копеек».

В акте выполненных работ сумму принято дублировать словами — так документ
нельзя «дорисовать» единицей и его принимает бухгалтерия. Считаем до
999 999 ₽: смена столько не стоит с большим запасом.
"""

_ONES_M = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять")
_ONES_F = ("", "одна", "две", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять")
_TEENS = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать",
          "девятнадцать")
_TENS = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
         "семьдесят", "восемьдесят", "девяносто")
_HUNDREDS = ("", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот")


def plural(n: int, one: str, few: str, many: str) -> str:
    """Русское склонение после числа: 1 рубль, 2 рубля, 5 рублей."""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def _triple(n: int, female: bool) -> list[str]:
    """Три разряда (0..999) словами."""
    words: list[str] = []
    if n >= 100:
        words.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        words.append(_TEENS[n - 10])
        return words
    if n >= 20:
        words.append(_TENS[n // 10])
        n %= 10
    if n:
        words.append((_ONES_F if female else _ONES_M)[n])
    return words


def rubles_in_words(amount: int) -> str:
    """Целые рубли прописью с копейками (копеек в сервисе не бывает).

    На сумме от миллиона функция бросала исключение, и весь документ отвечал
    500-й. А миллион достижим штатно: схема разрешает ставку до 1 000 000 ₽,
    да и долг заведения за месяц столько набрать может. Документ важнее
    красоты прописи — на больших суммах печатаем цифрами.
    """
    if amount < 0:
        raise ValueError("сумма акта не может быть отрицательной")
    if amount >= 1_000_000:
        return f"{amount:,} рублей 00 копеек".replace(",", " ")

    words: list[str] = []
    thousands, rest = divmod(amount, 1000)
    if thousands:
        # Тысяча — женского рода: «одна тысяча», «две тысячи».
        words += _triple(thousands, female=True)
        words.append(plural(thousands, "тысяча", "тысячи", "тысяч"))
    if rest or not thousands:
        words += _triple(rest, female=False)
    if amount == 0:
        words = ["ноль"]

    text = " ".join(w for w in words if w)
    unit = plural(amount, "рубль", "рубля", "рублей")
    return f"{text.capitalize()} {unit} 00 копеек"
