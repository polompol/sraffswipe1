# Как люди пишут города на самом деле. Слева — то, что могли ввести руками
# (в старых анкетах или через API), справа — каноническое название.
_ALIASES: dict[str, str] = {
    "спб": "Санкт-Петербург",
    "с-пб": "Санкт-Петербург",
    "санкт петербург": "Санкт-Петербург",
    "питер": "Санкт-Петербург",
    "мск": "Москва",
    "нижний": "Нижний Новгород",
    "нн": "Нижний Новгород",
    "ростов": "Ростов-на-Дону",
    "ростов на дону": "Ростов-на-Дону",
    "екб": "Екатеринбург",
    "нск": "Новосибирск",
    "челны": "Набережные Челны",
}


def _key(name: str) -> str:
    """Приводим написание к сравнимому виду: регистр, ё, дефисы, пробелы."""
    s = (name or "").strip().lower().replace("ё", "е")
    return " ".join(s.replace("-", " ").split())


_BY_KEY: dict[str, tuple[str, str]] = {_key(n): (n, tz) for n, tz in CITIES}


def normalize(name: str) -> str:
    """Каноническое название города или то, что ввели, если города нет в списке.

    Не запрещаем незнакомые города: маленький посёлок должен работать, просто
    по поясу по умолчанию. Но «Питер» и «спб» превращаются в
    «Санкт-Петербург», иначе эти люди не увидят друг друга.
    """
    raw = (name or "").strip()
    if not raw:
        return ""
    k = _key(raw)
    k = _key(_ALIASES.get(k, k))
    found = _BY_KEY.get(k)
    return found[0] if found else raw


def city_tz(name: str) -> str:
    """Часовой пояс города. Пусто — если город неизвестен (решает вызывающий)."""
    k = _key(name)
    k = _key(_ALIASES.get(k, k))
    found = _BY_KEY.get(k)
    return found[1] if found else ""


def same_city(a: str, b: str) -> bool:
    """Один ли это город. Сравнивать строки напрямую нельзя — см. алиасы."""
    return _key(normalize(a)) == _key(normalize(b))
