"""Должности по-русски — одно место на весь backend.

Раньше этот словарь был скопирован трижды (акт, счёт, админка), и копии
разошлись: в админке ключи `runner` и `manager` не существуют в природе —
на самом деле это `waiter_assistant` и `administrator`, — поэтому оператор
видел в жалобах «waiter_assistant · 300₽».

Хуже, что в трёх местах перевода не было вовсе, и латиница уходила прямо
в Telegram живым людям: «Срочно нужен человек: waiter», «Новая смена по
вашему поиску: cook, 300 ₽», дайджест «barista · 300₽ · 2026-08-12».

Список — зеркало StaffRole из app/schemas.py и tma/src/types/domain.ts.
"""

ROLE_RU: dict[str, str] = {
    "waiter": "Официант",
    "waiter_assistant": "Помощник официанта",
    "barista": "Бариста",
    "cook": "Повар",
    "dishwasher": "Посудомойщик",
    "hostess": "Хостес",
    "bartender": "Бармен",
    "hookah": "Кальянщик",
    "florist": "Флорист",
    "administrator": "Администратор",
    "courier": "Курьер",
    "cleaner": "Уборщик",
}


def role_ru(role: str) -> str:
    """Русское название должности. Незнакомое значение отдаём как есть —
    в базе могли остаться смены, созданные до закрытого списка."""
    return ROLE_RU.get(role, role)


def date_ru(iso: str) -> str:
    """2026-08-12 → 12.08. В сообщении человеку год не нужен, а «2026-08-12»
    читается как машинный код."""
    parts = (iso or "").split("-")
    if len(parts) != 3:
        return iso or ""
    return f"{parts[2]}.{parts[1]}"


def time_ru(minutes: int) -> str:
    """Минуты от полуночи → «10:00». Одна копия на весь сервер: раньше эта
    функция была написана заново в четырёх файлах."""
    return f"{minutes // 60:02d}:{minutes % 60:02d}"
