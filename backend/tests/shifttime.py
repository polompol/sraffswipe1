"""Перемотать смену в прошлое — одинаково для всех тестов.

Закрыть смену, отметить неявку и уточнить часы можно только ПОСЛЕ её
окончания, поэтому почти каждому тесту про закрытие нужно сначала довести
смену до конца.

Раньше каждый файл делал это сам: «дата = сегодня минус сутки». Это ломалось
дважды и по-разному, оба раза — в зависимости от времени суток на сервере:

1. «Сегодня» считали по UTC, а время смены живёт по местному поясу. После
   21:00 UTC московская дата уже следующая, и «вчерашняя» смена оказывалась
   старше суток — окно правки часов (ровно сутки) закрывалось, и тесты про
   часы падали по вечерам при исправном коде.
2. Даже с местным календарём «минус сутки» — это НЕ «сутки назад». В 00:40 по
   Москве вчерашняя смена 10:00–18:00 закончилась всего шесть часов назад, а
   расчёт по смене требует двенадцати: тест про закрытие смены падал ночью.

Поэтому здесь считается не календарь, а РАССТОЯНИЕ ДО КОНЦА СМЕНЫ: сколько
времени реально прошло с момента, когда смена закончилась. Это единственная
величина, от которой зависят все правила сервиса, и она не зависит от того,
в котором часу запустили тесты.
"""
from datetime import UTC, datetime, timedelta

from app.db import SessionLocal
from app.models import Match, Vacancy
from app.timeutil import local_now, shift_end_utc


def age_shift(match_id: str, days: int = 0) -> None:
    """Сдвинуть смену так, чтобы с её окончания прошло не меньше `days` суток.

    `days=0` — смена только что закончилась: все суточные окна (правка часов,
    отметка кодом) ещё открыты. Больше нуля — прошло столько суток и больше:
    так проверяют расчёт по смене (12 часов), просрочку и «слишком старую»
    смену, которую расчёт уже не трогает.
    """
    db = SessionLocal()
    try:
        m = db.get(Match, match_id)
        v = db.get(Vacancy, m.vacancy_id)
        now = datetime.now(UTC)
        want = timedelta(days=days)
        day = local_now(v.city).date()
        # Шагаем назад по календарю, пока с конца смены не пройдёт `days` суток.
        # Потолок в год — страховка от вечного цикла на битых данных.
        for _ in range(366):
            end = shift_end_utc(day.isoformat(), v.start_time, v.end_time, v.city)
            if now - end >= want:
                break
            day -= timedelta(days=1)
        # Помощник обязан выполнить своё обещание. Без этой проверки он
        # молча отдавал смену «моложе», чем просили, и тест падал уже в
        # другом месте — с сообщением, по которому причину не найти.
        end = shift_end_utc(day.isoformat(), v.start_time, v.end_time, v.city)
        assert now - end >= want, (
            f"не удалось состарить смену на {days} сут.: "
            f"конец смены {end}, сейчас {now}"
        )
        v.date = day.isoformat()
        db.commit()
    finally:
        db.close()
