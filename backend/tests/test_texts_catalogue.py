"""Список того, что сервис говорит человеку, не должен отставать от кода.

Список собирается из кода (scripts/texts.py), а не пишется руками — именно
потому, что рукописный расходится с кодом на второй неделе: правят в одном
месте, забывают в другом, и документ начинает врать.

Но собранный однажды он тоже устареет, если о нём забыть. Здесь проверяется
ровно это: пересобери — и получится тот же файл. Если нет, значит тексты
поменяли, а список не обновили.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def test_catalogue_matches_the_code():
    doc = ROOT / "docs" / "ТЕКСТЫ.md"
    assert doc.exists(), (
        "список текстов пропал — соберите: python3 scripts/texts.py --write"
    )

    fresh = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "texts.py")],
        capture_output=True, text=True, timeout=60,
    )
    assert fresh.returncode == 0, fresh.stderr[-2000:]
    assert fresh.stdout.strip() == doc.read_text().strip(), (
        "тексты в коде изменились, а docs/ТЕКСТЫ.md — нет.\n"
        "Соберите заново: python3 scripts/texts.py --write"
    )


def test_the_catalogue_actually_found_things():
    """Страховка от «сборщик сломался и молча выдал пустоту»."""
    text = (ROOT / "docs" / "ТЕКСТЫ.md").read_text()
    assert text.count("\n- ") > 100, "фраз подозрительно мало — сборщик сломан?"
    # Самое важное сообщение сервиса: единственный путь человека к спору.
    assert "несостоявшуюся" in text


def test_collector_does_not_choke_on_awkward_files():
    """Сборщик не должен вставать намертво на неудобном файле.

    Нашёл это не человек и не тест, а CodeQL: «Inefficient regular expression»
    в scripts/texts.py. В выражении для многострочных констант пробелы были
    записаны как \\s, а \\s включает перевод строки — и «\\s*\\n» одной строки
    делило одни и те же символы с «\\s*» следующей. У движка появлялось
    экспоненциально много способов разбить один и тот же кусок текста, и на
    неподходящем конце он перебирал их все.

    Замерено на настоящем выражении: 22 пары строк — 1,2 секунды, каждые
    следующие четыре умножают время примерно на шестнадцать. Сорок строк — уже
    часы. Сборщик ходит по всем файлам проекта и запускается в сборке.

    Отдельно стоит запомнить, КАК я это упустил. Увидев находку, я сам проверил
    выражение на откат, подобрал слабый вход, ничего не увидел и написал
    «чисто». Замер без правильного входа доказывает ровно одно: вход был
    неправильный. Поэтому вход зафиксирован здесь, а не придумывается заново.

    Замер идёт В ОТДЕЛЬНОМ ПРОЦЕССЕ, и вот почему. Первая версия проверки
    делала поиск прямо здесь — и на плохом выражении не упала, а ПОВИСЛА:
    прервать поиск по регулярному выражению внутри своего же потока нельзя.
    Висящая проверка хуже падающей: падение видно сразу и с причиной, а
    зависание выглядит как «сборка ещё идёт» и съедает время до общего
    потолка. Отдельный процесс убивается по таймауту, и зависание становится
    обычным отказом.

    Проверка по времени, а не по виду выражения: она переживёт любую переделку
    сборщика и сработает на любом новом выражении с тем же дефектом.
    """
    probe = r"""
import re, sys, time, json
src = open(sys.argv[1], encoding="utf-8").read()
awkward = '_X = (\n' + '"a"\n\n' * 24 + 'detail=\n' + '"b"\n\n' * 24 + 'ОБРЫВ'
slow = []
for p in re.findall(r"r'((?:[^'\\]|\\.)*)'", src):
    try:
        rx = re.compile(p, re.M)
    except re.error:
        continue
    t = time.monotonic()
    rx.search(awkward)
    d = time.monotonic() - t
    if d > 0.5:
        slow.append([round(d, 2), p[:70]])
print(json.dumps(slow))
"""
    script = ROOT / "scripts" / "texts.py"
    try:
        r = subprocess.run(
            [sys.executable, "-c", probe, str(script)],
            capture_output=True, text=True, timeout=30,
        )
    except subprocess.TimeoutExpired:
        raise AssertionError(
            "выражение сборщика ушло в перебор настолько, что не уложилось "
            "в 30 секунд на 24 строках. На реальном файле это часы."
        ) from None

    assert r.returncode == 0, r.stderr[-2000:]
    slow = json.loads(r.stdout)
    assert not slow, (
        "выражение сборщика уходит в перебор на неудобном тексте:\n"
        + "\n".join(f"  {t} с — {p}…" for t, p in slow)
    )
