import type { ReactNode } from "react";
import { IconBack, IconLike } from "@/components/Icons";
import { Button } from "@/components/Button";

/**
 * Изнанка свайп-карточки.
 *
 *  Раньше подробности открывались шторкой снизу. Шторка — отдельный слой
 *  поверх экрана: карточка уезжала под неё, и связь «это та же смена»
 *  держалась только на памяти. Переворот эту связь показывает: у карточки
 *  просто есть вторая сторона, и она никуда не уходит.
 *
 *  У изнанки СВОИ кнопки, а круглые кнопки колоды на время переворота
 *  прячутся. Сначала было наоборот — кнопки колоды оставались поверх изнанки,
 *  и это стоило трёх дефектов сразу: они съедали 96 точек высоты (на экране
 *  320×568 от подробностей оставалась одна строка, и ничто не подсказывало,
 *  что есть прокрутка), их белые подписи пропадали на светлом фоне, а нижняя
 *  строка изнанки заходила им под край. Свои кнопки внутри — как было у
 *  шторки — снимают всё три разом.
 *
 *  Заголовок, оговорка и кнопки прижаты к краям, прокручивается только
 *  середина: описание смены — свободный текст, и предугадать его длину нельзя.
 */
export function CardBack({
  title,
  note,
  primary,
  onPrimary,
  onBack,
  children,
}: {
  title: string;
  /** Оговорка, которую человек обязан увидеть. Стоит ВНЕ прокрутки: пока она
   *  была последней строкой содержимого, длинное описание уводило её под сгиб
   *  вместе с предупреждением про деньги вперёд. */
  note?: ReactNode;
  /** Подпись главного действия: у работника «Откликнуться», у заведения
   *  «Позвать». Заведение не откликается на человека, оно его зовёт. */
  primary: string;
  onPrimary: () => void;
  onBack: () => void;
  children: ReactNode;
}) {
  return (
    <div className="card-back-inner">
      <div className="card-back-head">{title}</div>
      <div className="card-back-scroll">{children}</div>
      {note && <div className="card-back-note">{note}</div>}
      <div className="card-back-foot">
        {/* block={false} обязателен: по умолчанию кнопка во всю ширину, и две
            такие в ряду просто вылезали бы за край карточки. */}
        {/* aria-label стоит всегда, а слово «Назад» на узком экране прячется
            (см. .card-back-foot .foot-word в CSS). Замер на 320 точках: «Назад»
            занимал 114 точек и не сжимался, и главной кнопке оставалось 132 —
            «Откликнуться» в них не помещалось и обрезалось на середине слова.
            Незрячему при этом ничего не теряется: имя кнопки от вида не
            зависит, а стрелка влево понятна и без подписи. */}
        <Button
          variant="secondary"
          block={false}
          aria-label="Назад"
          style={{ flex: "0 0 auto" }}
          icon={<IconBack size={16} />}
          onClick={onBack}
        >
          <span className="foot-word">Назад</span>
        </Button>
        <Button
          block={false}
          style={{ flex: "1 1 auto", minWidth: 0 }}
          icon={<IconLike size={18} />}
          onClick={onPrimary}
        >
          {primary}
        </Button>
      </div>
    </div>
  );
}
