import type { ReactNode } from "react";
import { IconBack } from "@/components/Icons";
import { Button } from "@/components/Button";

/**
 * Изнанка свайп-карточки — место, где ЧИТАЮТ. Решают на лицевой стороне.
 *
 *  Раньше подробности открывались шторкой снизу. Шторка — отдельный слой
 *  поверх экрана: карточка уезжала под неё, и связь «это та же смена»
 *  держалась только на памяти. Переворот эту связь показывает.
 *
 *  Здесь НЕТ главного действия, и это осознанно. Сначала было: «Назад» и
 *  «Откликнуться». Получалась кривая пара — согласиться с изнанки можно, а
 *  отказаться нет, хотя подробности читают ровно затем, чтобы решить, и
 *  половина решений будет «не моё»: далеко ехать, смена ночная, дресс-код не
 *  подходит. Человек дочитывал, понимал «нет» — и упирался в кнопку, которая
 *  предлагала «да».
 *
 *  Теперь оба ответа живут в одном месте — на лицевой стороне, где и свайп, и
 *  две круглые кнопки. Изнанка возвращает карточку и не решает ничего.
 *
 *  Кнопка «Назад» остаётся, хотя карточка переворачивается и касанием: касание
 *  недоступно тому, кто ходит по экрану клавиатурой или переключателем, и без
 *  кнопки изнанка была бы для него ловушкой без выхода.
 *
 *  Заголовок, оговорка и кнопка прижаты к краям, прокручивается только
 *  середина: описание смены — свободный текст, и предугадать его длину нельзя.
 */
export function CardBack({
  title,
  note,
  onBack,
  children,
}: {
  title: string;
  /** Оговорка, которую человек обязан увидеть. Стоит ВНЕ прокрутки: пока она
   *  была последней строкой содержимого, длинное описание уводило её под сгиб
   *  вместе с предупреждением про деньги вперёд. */
  note?: ReactNode;
  onBack: () => void;
  children: ReactNode;
}) {
  return (
    <div className="card-back-inner">
      <div className="card-back-head">{title}</div>
      <div className="card-back-scroll">{children}</div>
      {note && <div className="card-back-note">{note}</div>}
      {/* Нажатие на кнопку не должно всплывать до карточки: касание карточки
          переворачивает её, и «Назад» срабатывал, а следом карточка тут же
          переворачивалась обратно — кнопка отменяла сама себя. Ловится только
          сквозным тестом: по коду каждая половина верна. */}
      <div className="card-back-foot" onClick={(e) => e.stopPropagation()}>
        <Button
          variant="secondary"
          size="sm"
          block={false}
          icon={<IconBack size={16} />}
          onClick={onBack}
        >
          Назад к карточке
        </Button>
      </div>
    </div>
  );
}
