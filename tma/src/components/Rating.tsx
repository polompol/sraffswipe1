import { IconStar } from "@/components/Icons";
import { dec1 } from "@/lib/format";

/**
 * Оценка человека или заведения: «★ 4,8», а у неоценённых — «Новичок».
 *
 * Собиралась вручную в четырёх местах, и каждый раз чуть иначе: где-то
 * звезда 12 точек, где-то 13 или 14; где-то ноль показывали как «★ 0,0» —
 * на глаз это худший возможный рейтинг, хотя человека просто ещё никто не
 * оценил. Правило одно: рейтинга нет — так и говорим словом.
 */
export function Rating({ value, size = 13 }: { value?: number; size?: number }) {
  if (!value || value <= 0) return <>Новичок</>;
  return (
    <>
      <IconStar size={size} /> {dec1(value)}
    </>
  );
}
