/**
 * Ключи, которые мы когда-то писали и больше не пишем. Перестать сохранять —
 * половина дела: у того, кто пользовался приложением раньше, старое значение
 * так и лежит в телефоне и само оттуда не денется. Здесь мы его стираем при
 * запуске.
 *
 * ss_geo — точные координаты устройства для ленты «смены рядом».
 */
const RETIRED = ["ss_geo"];

/** Убрать из хранилища то, что мы больше не храним. Вызывается один раз при старте. */
export function forgetRetired(): void {
  try {
    for (const k of RETIRED) localStorage.removeItem(k);
  } catch {
    /* приватный режим — хранилища нет, стирать нечего */
  }
}

