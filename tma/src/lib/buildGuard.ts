/** БОЕВАЯ СБОРКА НЕ ДОЛЖНА СОБРАТЬСЯ НА ДЕМО-ДАННЫХ.
 *
 *  Без backend приложение работает на выдуманных сменах — это удобно для
 *  показа и для локальной работы. Но если такая сборка уедет на сервер,
 *  поломки не будет видно вообще: приложение откроется, лента заполнится,
 *  люди начнут откликаться на смены, которых нет, и заведения не получат ни
 *  одного отклика. Никакой ошибки при этом никто не увидит.
 *
 *  Поэтому боевая сборка (её помечает docker-compose.prod.yml переменной
 *  PROD_BUILD=1) падает сразу, если демо-режим не выключен. Обычные сборки —
 *  локальная и в CI — этой проверки не касаются.
 *
 *  Проверка вынесена из vite.config.ts отдельным файлом ровно затем, чтобы её
 *  можно было прогнать тестом: предохранитель, который сам никем не проверен,
 *  однажды перестаёт срабатывать молча.
 */
export function assertNotDemoBuild(env: Record<string, string | undefined>): void {
  if (env.PROD_BUILD !== "1") return;
  if (env.VITE_USE_BACKEND === "true") return;
  throw new Error(
    "Боевая сборка с демо-данными: VITE_USE_BACKEND должен быть \"true\". "
    + "Проверьте args в docker-compose.prod.yml — приложение уехало бы на "
    + "сервер с выдуманными сменами.",
  );
}
