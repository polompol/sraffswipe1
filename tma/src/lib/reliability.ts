import { plural } from "./format";

/** Процент выходов: «92%». Пусто, если смен ещё не было.
 *
 *  Округляем ВНИЗ: 39 из 40 — это 97%, а не 98%. Человеку, который выбирает,
 *  кого пустить к кассе, лучше слегка недосказать, чем слегка приукрасить.
 */
export function attendanceRate(
  shiftsTotal?: number,
  shiftsAttended?: number,
): string {
  if (!shiftsTotal) return "";
  return `${Math.floor(((shiftsAttended ?? 0) / shiftsTotal) * 100)}%`;
}

/** Надёжность человека одной строкой: «92% из 12 смен · 3 заведения».
 *
 *  Число РАЗНЫХ заведений здесь не для красоты. Пять смен с пятью заведениями
 *  и пять смен с одним — разный опыт и разная степень доверия, а по одному
 *  счётчику смен их не отличить. Именно на этом держалась накрутка: пара
 *  сговорившихся аккаунтов (или один человек с двумя Telegram) закрывает
 *  смену за сменой, и в ленте появляется безупречная история.
 *
 *  Раньше строка была длиннее: «92% выходов · вышел на 11 из 12 смен · 3
 *  заведения». Процент и «11 из 12» — одна и та же мысль, сказанная дважды,
 *  на карточке, которую листают одной рукой. Плюс «вышел» — мужской род, а
 *  половина бариста и официантов — женщины. Объём смен при этом важен и
 *  остался: «92% из 12 смен» — это и надёжность, и сколько за ней стоит.
 *
 *  У новичка строки нет вовсе — врать про «0 из 0» не нужно.
 */
export function reliabilityText(
  shiftsTotal?: number,
  shiftsAttended?: number,
  employersTotal?: number,
): string {
  const rate = attendanceRate(shiftsTotal, shiftsAttended);
  if (!rate) return "";
  // Процент без объёма обманчив: 100% из одной смены и 100% из сорока —
  // разный разговор, а решение «беру или нет» принимают по этой строке.
  const base = `${rate} из ${shiftsTotal} ${plural(shiftsTotal ?? 0, "смены", "смен", "смен")}`;
  const n = employersTotal ?? 0;
  if (!n) return base;
  return `${base} · ${n} ${plural(n, "заведение", "заведения", "заведений")}`;
}
