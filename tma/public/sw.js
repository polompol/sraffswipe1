/**
 * Service worker минимальный и НАМЕРЕННО без кэша.
 *
 * Он нужен ровно для одного: без обработчика fetch браузер не считает сайт
 * устанавливаемым и не предлагает «Добавить на главный экран». Кэшировать же
 * тут нечего и опасно: приложение почти целиком — живые данные (лента смен,
 * чат, баланс), а устаревшая версия оболочки после обновления сервера
 * означала бы, что человек смотрит вчерашние смены и не понимает почему.
 *
 * Регистрируется только вне Telegram (см. main.tsx): внутри Mini App
 * приложение и так живёт в оболочке Telegram, лишний слой там не нужен.
 */
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));
self.addEventListener("fetch", () => {
  /* Ничего не перехватываем: всё уходит в сеть как обычно. */
});
